#!/usr/bin/env python3
"""Generate design-only OR/XOR/ANDNOT derivations from A/C, never direct facts."""
from pathlib import Path

ROOT = Path(__file__).resolve().parent
WIDTHS = (8, 16, 32, 64)


def generate(n):
    m = 1 << n
    x = f'(a as bv{n})'
    y = f'(b as bv{n})'
    u = lambda e: f'(({e}) as int)'
    xn, yn = f'!{x}', f'!{y}'
    andc = f'({xn}&{yn})'
    andab = f'({x}&{y})'
    orab = f'({x}|{y})'
    notand = f'!{andab}'
    content = f'''// Generated by generate.py. Design-only local-fact projection.
// Assumptions below are ONLY guarded A/C basis instances.
include "reference.dfy"
include "native-identities.dfy"

lemma {{:induction false}} {{:isolate_assertions}} {{:resource_limit 2000000}} derive_or{n}(a: nat,b: nat)
  requires a < {m} && b < {m}
  ensures {u(orab)} == orNat({n},a,b)
{{
  power{n}();
  nativeOr{n}({x},{y});
  orExpand({n},a,b);
  // C composed at each checked source cast; C raw at the outer complement.
  assume {{:axiom}} 0 <= a < {m} ==> {u(xn)} == {m-1}-a;
  assume {{:axiom}} 0 <= b < {m} ==> {u(yn)} == {m-1}-b;
  // A raw at the AND of the two complements.
  assume {{:axiom}} {u(andc)} == andNat({n},{u(xn)},{u(yn)});
  assume {{:axiom}} {u('!'+andc)} == {m-1}-{u(andc)};
  calc {{
    {u(orab)};
    == {u('!'+andc)};
    == {m-1}-{u(andc)};
    == {m-1}-andNat({n},{u(xn)},{u(yn)});
    == {m-1}-andNat({n},{m-1}-a,{m-1}-b);
    == orNat({n},a,b);
  }}
}}

lemma {{:induction false}} {{:isolate_assertions}} {{:resource_limit 2000000}} derive_xor{n}(a: nat,b: nat)
  requires a < {m} && b < {m}
  ensures {u(f'({x}^{y})')} == xorNat({n},a,b)
{{
  power{n}();
  derive_or{n}(a,b);
  nativeXor{n}({x},{y});
  xorExpand({n},a,b);
  // A composed at the checked input casts.
  assume {{:axiom}} 0 <= a < {m} && 0 <= b < {m}
    ==> {u(andab)} == andNat({n},a,b);
  // C raw, then A raw, for the actual native XOR decomposition.
  assume {{:axiom}} {u(notand)} == {m-1}-{u(andab)};
  assume {{:axiom}} {u(f'({orab}&{notand})')} ==
    andNat({n},{u(orab)},{u(notand)});
  calc {{
    {u(f'({x}^{y})')};
    == {u(f'({orab}&{notand})')};
    == andNat({n},{u(orab)},{u(notand)});
    == andNat({n},orNat({n},a,b),{m-1}-andNat({n},a,b));
    == xorNat({n},a,b);
  }}
}}

lemma {{:induction false}} {{:isolate_assertions}} {{:resource_limit 2000000}} derive_andnot{n}(a: nat,b: nat)
  requires a < {m} && b < {m}
  ensures {u(f'({x}&{yn})')} == andNotNat({n},a,b)
{{
  power{n}();
  andNotExpand({n},a,b);
  // Existing guarded round-trip family (#33); this assertion is proved.
  assert {u(x)} == a;
  // C composed and A raw, with no ANDNOT axiom.
  assume {{:axiom}} 0 <= b < {m} ==> {u(yn)} == {m-1}-b;
  assume {{:axiom}} {u(f'({x}&{yn})')} == andNat({n},{u(x)},{u(yn)});
  calc {{
    {u(f'({x}&{yn})')};
    == andNat({n},{u(x)},{u(yn)});
    == andNat({n},a,{m-1}-b);
    == andNotNat({n},a,b);
  }}
}}
'''
    for op, expr, ref in [('or', orab, 'orNat'), ('xor', f'({x}^{y})', 'xorNat'), ('andnot', f'({x}&{yn})', 'andNotNat')]:
        content += f'''
lemma {{:induction false}} client_{op}{n}(a: nat,b: nat)
  requires a < {m} && b < {m}
  ensures {u(expr)} == {ref}({n},a,b)
{{ derive_{op}{n}(a,b); }}

lemma {{:induction false}} control_{op}{n}()
{{
  smallReference({n});
  derive_{op}{n}(5,3);
  assert {{:split_here}} false;
}}
'''
    return content


def main():
    for n in WIDTHS:
        (ROOT / f'w{n}-derived-boolean.dfy').write_text(generate(n))


if __name__ == '__main__':
    main()
